const fs = require("node:fs");
const path = require("node:path");

const sourceFiles = [
  "plugin-source.js",
  "backup-service.js",
  "progress-modal.js",
  "settings-tab.js",
  "settings.js",
];

const moduleFactories = sourceFiles.map((fileName) => {
  const moduleId = `./${fileName}`;
  const source = fs.readFileSync(path.join(__dirname, fileName), "utf8");
  return `${JSON.stringify(moduleId)}: function (require, module, exports) {\n${source}\n}`;
});

const bundle = `// Generated by build.js. Edit the source modules instead.
const externalRequire = require;
const path = externalRequire("path");
const moduleFactories = {
${moduleFactories.join(",\n")}
};
const moduleCache = new Map();

function resolveRelativeModule(parentId, request) {
  const resolved = path.posix.normalize(
    path.posix.join(path.posix.dirname(parentId), request),
  );
  const moduleId = resolved.startsWith(".") ? resolved : \`./\${resolved}\`;
  return moduleId.endsWith(".js") ? moduleId : \`\${moduleId}.js\`;
}

function loadModule(id) {
  if (moduleCache.has(id)) {
    return moduleCache.get(id).exports;
  }

  const factory = moduleFactories[id];
  if (!factory) {
    throw new Error(\`Cannot find bundled module "\${id}".\`);
  }

  const module = { exports: {} };
  moduleCache.set(id, module);
  const localRequire = (request) =>
    request.startsWith(".")
      ? loadModule(resolveRelativeModule(id, request))
      : externalRequire(request);

  factory(localRequire, module, module.exports);
  return module.exports;
}

module.exports = loadModule("./plugin-source.js");
`;

fs.writeFileSync(path.join(__dirname, "main.js"), bundle);
